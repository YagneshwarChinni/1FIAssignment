export interface EmiPlan {
  id: string;
  months: number;
  monthlyAmount: number;
  totalAmount: number;
  interestRate: number;
  processingFee: number;
  bank: string;
}

export interface ProductVariant {
  id: string;
  label: string;
  priceModifier: number;
}

export interface Product {
  id: string;
  name: string;
  brand: string;
  category: string;
  basePrice: number;
  mrp: number;
  discount: number;
  rating: number;
  reviewCount: number;
  image: string;
  badge?: string;
  description: string;
  highlights: string[];
  variantGroups: { label: string; variants: ProductVariant[] }[];
  emiPlans: EmiPlan[];
}

const BANKS = ["HDFC Bank", "ICICI Bank", "Axis Bank", "SBI Card", "Kotak Bank"];

function makeEmis(price: number, nocost: number[] = [3], paid: number[] = [6, 12]): EmiPlan[] {
  const plans: EmiPlan[] = [];
  nocost.forEach((m, i) => {
    plans.push({ id: `nc${i}`, months: m, monthlyAmount: Math.round(price / m), totalAmount: price, interestRate: 0, processingFee: 0, bank: "1Fi No-Cost EMI" });
  });
  paid.forEach((m, i) => {
    const rate = 1.5;
    const total = Math.round(price * (1 + (rate / 100) * (m / 12)));
    plans.push({ id: `p${i}`, months: m, monthlyAmount: Math.round(total / m), totalAmount: total, interestRate: rate, processingFee: m <= 6 ? 199 : 299, bank: BANKS[i % BANKS.length] });
  });
  return plans;
}

